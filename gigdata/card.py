"""Generates docs/DATA_CARD.md from the real manifests and code constants, so the card cannot drift from the code.

python -m gigdata.card
"""
from __future__ import annotations

import inspect
import json
from pathlib import Path

import yaml

from gigdata import real, synth
from gigdata.text import SIGNALS

ROOT = Path(__file__).resolve().parents[1]


def md_table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build() -> str:
    src = yaml.safe_load((ROOT / "data/sources.yaml").read_text())
    man = json.loads((ROOT / "data/synthetic/MANIFEST.json").read_text())
    real_man_path = ROOT / "data/processed/jobs_real.manifest.json"
    real_man = json.loads(real_man_path.read_text()) if real_man_path.exists() else None
    d = inspect.signature(real.normalise_row).parameters
    min_desc, min_ascii = d["min_desc"].default, d["min_ascii"].default
    dev = man["summary"]["dev"]

    sources_rows = [[k, f"[{v['kaggle']}]({v['url']})", v["role"], v.get("claimed_size", "?"), v["licence"],
                     "downloaded" if (real_man and k in real_man["sources"] and real_man["sources"][k].get("rows_in")) else "NOT DOWNLOADED"]
                    for k, v in src["sources"].items()]
    if real_man:
        real_rows = [[k, v.get("rows_in", 0), v.get("kept", 0), json.dumps(v.get("dropped", {})), v.get("redactions", 0),
                      json.dumps(v.get("signals", {}))] for k, v in real_man["sources"].items()]
        real_block = md_table(["source", "rows in", "kept", "dropped (reason: count)", "redactions", "rule signals"], real_rows)
    else:
        real_block = ("_No real data has been processed yet._ Download the CSVs (needs a Kaggle login), put them in "
                      "`data/raw/<source_key>/`, then run `python -m gigdata.real schema|build|stats` and regenerate this card "
                      "(`python -m gigdata.card`). Counts will appear here automatically.")
    class_rows = [[k, v] for k, v in dev["by_class"].items()]
    sig_rows = [[k, len(v)] for k, v in SIGNALS.items()]

    return f"""# Data Card

_Generated by `python -m gigdata.card` from `data/sources.yaml`, `data/synthetic/MANIFEST.json` and the loader's code
constants. Do not edit by hand; edit the sources or the generator and regenerate._

## 1. Summary

| Data | Origin | Used for | Committed to git |
|---|---|---|---|
| Kaggle job-post datasets (6 listed, see section 2) | **Real** (third-party scrape) | job-side realism, market statistics, rule audit | **No** (licence unverified) |
| Freelancer personas, portfolios, reviews, past proposals, client histories, message threads, adversarial jobs | **Synthetic** (this repo's generator, seed {man['seed']}, v{man['generator_version']}) | everything with a freelancer or client on it, and all gold labels | Yes |
| Starter-kit samples (`data/kit_sample/`) and policy pack | Instructor-provided, synthetic/illustrative | schema reference, policy rules | Yes |
| GigSim, instructor personas, dev/test sets | Instructor-provided (**not in the starter kit zip**) | final grading | n/a: obtain from Classroom, never modify `gigsim/` |

Every record carries `origin: "real"` or `origin: "synthetic"` and, for jobs, a per-field `provenance` map.

## 2. Real sources: status, licence, attribution

{md_table(['key', 'dataset', 'role', 'claimed size', 'licence', 'status'], sources_rows)}

**Licence: UNVERIFIED for every source.** The licence and column lists could not be read from the Kaggle pages in the
development environment. Until each licence is confirmed on its Kaggle page, raw and processed real data are git-ignored
and only synthetic data is committed. Attribution to give when you cite them: the dataset author handle and URL above.
`trial_1` is unused: its contents were never inspected.

Common limitations:
{chr(10).join('- ' + x for x in src['limitations_common'])}

## 3. Real-data preprocessing (`gigdata/real.py`)

1. **Schema check first**: `python -m gigdata.real schema --source KEY` prints which column was mapped to which field and what is
   unmapped. Headers are matched by exact normalised alias (no fuzzy guessing); overrides go in `data/column_overrides.yaml`.
2. **Filters** (each drop is counted by reason in `jobs_real.manifest.json`): missing title; description shorter than
   **{min_desc}** characters; fewer than **{min_ascii:.0%}** ASCII characters (a crude English filter that will also drop
   legitimate non-English or heavily symbolic posts); duplicates.
3. **Rule signals computed on the raw text, then PII redaction** of emails, URLs and phone numbers (so contact details
   cannot reach the repo, but "contact me on WhatsApp" still raises `off_platform_contact`).
4. **Deduplication** by normalised title+description fingerprint, across all sources.
5. **Normalisation** to the starter-kit job schema (`required_skills`, `budget{{min,max}}`, `duration_days`, ...).
   Hourly vs fixed is kept in `pricing_type`. Duration labels are mapped to rough day counts.
6. **Synthesised fields**: `connects_cost` is not public data; it is assigned deterministically from a hash of the job id
   (8, 12 or 16) and marked `synthetic(deterministic hash)` in `provenance`. `screening_questions` are absent in scraped data.
7. **Market statistics** (`python -m gigdata.real stats`): per-skill quartiles of hourly and fixed budgets, only for skills with
   at least 30 observations.

Real-data results of the last run:

{real_block}

## 4. Synthetic data (`gigdata/synth.py`)

Deterministic and seeded: the same seed gives byte-identical files (checked in `tests/unit/test_synth.py` and by SHA-256 hashes in
`data/synthetic/MANIFEST.json`). Content tables are in `gigdata/synth_content.py`.

- **4 personas** (AI engineer, data engineer, full-stack web, mobile), each with 6 capabilities, producing per persona: a CV,
  case studies, repository READMEs, client reviews and 10 past proposals with outcomes.
- **Splits**: `dev` (for tuning) and `holdout` (different seed; run once at the end). Both come from the **same generator and
  templates**, so the holdout tests overfitting to dev examples but **not** distribution shift.
- **Per split, per persona**, jobs by class: {', '.join(f'{k} {v // 4}' for k, v in dev['by_class'].items())} ({dev['jobs']} jobs, {dev['threads']} message threads in total).

{md_table(['class (dev, all personas)', 'jobs'], class_rows)}

### Rules that define the gold labels (so nobody mistakes them for measured reality)
- **Proposal outcome**: P(reply) = 0.38 for "specific" proposals and 0.10 for "generic" ones; P(won | reply) = 0.30. The
  specific/generic label is kept in `data/synthetic/_ground_truth/` and not shown to the system.
- **Job gold action**: `bid` if the persona can evidence at least 60% of the requirements, `watch` at 30-60%, else `skip`;
  always `skip` for scams, injections, risky clients, out-of-scope domains and budgets far below scope.
- **Fair price band** = [max(budget_min, 0.85 x expected), min(budget_max, 1.3 x expected)] with expected = hourly rate x hours(n requirements).
- **Retrieval gold** for a requirement = the persona's case studies, repositories and reviews for that capability. Past proposals
  are never gold: they are the freelancer's own claims, not proof.
- Gold labels live only in `evals/datasets/synth_*` and `data/synthetic/_ground_truth/`, never in marketplace-facing files
  (checked by `test_no_gold_leaks_into_marketplace_data`).

### Deliberate hard cases
- Client wording of each need (`asks`) deliberately differs from portfolio wording (vocabulary gap), so exact-match retrieval is
  not enough.
- **Evasive scams** and messages avoid the most obvious keywords at generation time. **Caveat**: the shared rule set
  (`agent/rules.py`, {sum(len(v) for v in SIGNALS.values())} patterns in {len(SIGNALS)} signal types) was broadened after reading the dev templates, so it also catches
  several "evasive" ones. Rule recall on dev **and** holdout is therefore inflated by shared template vocabulary.
- **Lookalike jobs** contain phrases such as "ignore the previous brief" or "write a good system prompt": legitimate posts that
  must not be flagged. Gold = bid, injection = false.
- Injection attempts are placed at the start or end of otherwise normal posts.

## 5. Known limitations and biases
- Synthetic text is template-generated: far less varied than real posts, with clean grammar and a small closed vocabulary.
  Retrieval and classification scores on it **will overstate** real-world performance and must be reported as "synthetic dev/holdout".
- Gold labels follow the generator's own rules, so systems that implement those rules score well by construction.
- Proposal outcomes follow a stated probability rule; any "outcome-aware" gain measured here shows the code works, not that the effect exists.
- Only fixed-price synthetic jobs; no timezones, languages or currencies; four technical personas only.
- Real posts: single time window, one marketplace, scraped (selection bias), English-leaning after filtering; skills and
  budgets are as entered by clients and are noisy; no outcomes or conversations exist at all.
- Stand-ins in the evaluation harness (placeholder hashed embedder, lexical reranker, lexical grader) are named in every
  result file's `meta`. Replace them (nomic-embed-text / bge-reranker-v2-m3 / LLM grader) before reporting retrieval numbers.

## 6. Licensing, attribution and handling
- **Kaggle sources**: licence UNVERIFIED (section 2). Do not commit or redistribute raw or processed real data until confirmed.
  Platform terms of the original marketplace may also restrict reuse of scraped content. The assignment forbids scraping
  Upwork ourselves; we only reuse data others published.
- **Starter kit**: instructor-provided; its data are synthetic examples; its policy pack is illustrative and the instructor's pack is
  the grading source of truth.
- **Synthetic data**: generated by this repository (code and content tables are original work, authored with AI assistance; see
  `docs/AI_USAGE.md`); all people, companies, phone numbers and emails are fictional (reserved `555-01xx` numbers and `example.com`).
  Choose and add a licence for the repository.
- **Privacy**: real posts can contain personal data. The loader redacts emails, URLs and phone numbers before storage; names in
  free text are not redacted. `.env`, `data/raw/` and `data/processed/` are git-ignored.

## 7. Evaluation protocol
- Tune and debug on `dev` only. Run `holdout` once per final system and report it separately; never tune on it.
- The only non-circular check of the rule detector is a **human audit on real posts**: `python -m gigdata.audit sample` then
  label then `score` (see `gigdata/audit.py`). Until that is done, state that rule quality on real posts is unmeasured.
- Every reported number must trace to a file in `evals/results/`.

## 8. Reproduce
```
python -m gigdata.synth                      # regenerate data/synthetic and evals/datasets/synth_* (deterministic)
python -m gigdata.real schema --source KEY   # then build / stats once CSVs are in data/raw/KEY/
python -m gigdata.card                       # regenerate this card
make eval-synth                              # variant comparison, ablation, decision and intent baselines on dev
```
"""


if __name__ == "__main__":
    out = ROOT / "docs" / "DATA_CARD.md"
    out.write_text(build())
    print("wrote", out)
