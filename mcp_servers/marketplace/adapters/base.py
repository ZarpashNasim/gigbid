"""What the Marketplace MCP server needs from a backend. GigSim and live-Upwork adapters implement this."""
from __future__ import annotations

from typing import Protocol


class Backend(Protocol):
    def search_jobs(self, query: str, limit: int) -> list[dict]: ...
    def get_job(self, job_id: str) -> dict: ...
    def get_client_history(self, client_id: str) -> dict: ...
    def get_connects_balance(self) -> int: ...
    def list_messages(self, thread_id: str) -> list[dict]: ...
    def connects_cost(self, job_id: str) -> int: ...
    def create_proposal(self, job_id: str, cover_letter: str, amount: float, answers: dict) -> dict: ...
    def submit_proposal(self, proposal_id: str) -> dict: ...
    def send_message(self, thread_id: str, body: str) -> dict: ...


class BackendUnavailable(Exception):
    """Timeouts / 5xx after retries."""
